// HTML / CSS / JS minification wrappers. Failures throw so the build fails loudly.
import { minify as minifyHtmlLib } from 'html-minifier-next';
import { transform as cssTransform } from 'lightningcss';
import { minify_sync as terserSync } from 'terser';

export class MinifyError extends Error {
  constructor(kind, file, cause) {
    super(`${kind} minification failed for ${file}: ${cause && cause.message ? cause.message : cause}`);
    this.name = 'MinifyError';
    this.cause = cause;
  }
}

export function minifyCss(code, { filename = 'inline.css' } = {}) {
  const res = cssTransform({ filename, code: Buffer.from(code), minify: true, errorRecovery: false });
  return Buffer.from(res.code).toString('utf8');
}

function minifyCssForHtml(text, type) {
  if (type === 'inline') {
    const wrapped = minifyCss(`x{${text}}`);
    const m = /^x\{([\s\S]*)\}$/.exec(wrapped.trim());
    return m ? m[1] : text;
  }
  if (type === 'media') return text.trim();
  return minifyCss(text);
}

export function minifyJs(code, { filename = 'inline.js', module = false } = {}) {
  const res = terserSync(code, {
    module,
    compress: { passes: 2, drop_debugger: true, pure_getters: false, unsafe: false },
    mangle: { safari10: true },
    format: { comments: /^!|@license|@preserve/ },
    sourceMap: false,
  });
  if (res.error) throw res.error;
  return res.code;
}

function minifyJsForHtml(text, inline) {
  return minifyJs(text, { filename: 'inline.js', module: false }).replace(/;$/, inline ? '' : ';');
}

export const HTML_MINIFY_OPTIONS = {
  collapseWhitespace: true,
  conservativeCollapse: true,
  preserveLineBreaks: false,
  removeComments: true,
  ignoreCustomComments: [/^!/, /^\s*#/, /^\s*\[if/, /^\s*<!\[endif/],
  minifyCSS: minifyCssForHtml,
  minifyJS: minifyJsForHtml,
  keepClosingSlash: true,
  caseSensitive: true,
  decodeEntities: false,
  includeAutoGeneratedTags: true,
  removeAttributeQuotes: false,
  removeEmptyAttributes: false,
  removeEmptyElements: false,
  removeOptionalTags: false,
  removeRedundantAttributes: false,
  collapseBooleanAttributes: false,
  useShortDoctype: false,
  sortAttributes: false,
  minifyURLs: false,
  continueOnParseError: false,
};

export function compactJsonLd(html) {
  return html.replace(/(<script[^>]*type=["']application\/ld\+json["'][^>]*>)([\s\S]*?)(<\/script>)/gi, (m, open, body, close) => {
    try { return `${open}${JSON.stringify(JSON.parse(body))}${close}`; } catch { return m; }
  });
}

export async function minifyHtml(html, { filename = 'index.html' } = {}) {
  try {
    return await minifyHtmlLib(compactJsonLd(html), HTML_MINIFY_OPTIONS);
  } catch (err) {
    throw new MinifyError('HTML', filename, err);
  }
}
